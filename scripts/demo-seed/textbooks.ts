export function pageHtml(page: DemoPage): string {
  const parts: string[] = [];
  if (page.h1) parts.push(`<h1>${page.h1}</h1>`);
  if (page.h2) parts.push(`<h2>${page.h2}</h2>`);
  if (page.index) {
    const lines = page.index.map(([title, printed]) => `${title} ${printed}`).join('<br>');
    parts.push(`<div data-category="index">${lines}</div>`);
  }
  for (const paragraph of page.paragraphs) parts.push(`<p>${paragraph}</p>`);
  return parts.join('\n');
}

export function pageMarkdown(page: DemoPage): string {
  const parts: string[] = [];
  if (page.h1) parts.push(`# ${page.h1}`);
  if (page.h2) parts.push(`## ${page.h2}`);
  if (page.index) parts.push(page.index.map(([title, printed]) => `- ${title} ${printed}`).join('\n'));
  parts.push(...page.paragraphs);
  return parts.join('\n\n');
}
